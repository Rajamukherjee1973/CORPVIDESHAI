// The reasons an Indian company lawfully sends investment money abroad, split
// the way the Foreign Exchange Management (Overseas Investment) Rules 2022
// splits them: Overseas Direct Investment (ODI) — control or a strategic stake
// in a foreign entity — and Overseas Portfolio Investment (OPI) — a financial
// holding with no control. Each entry carries the statutory hook the rail
// cites and the plain-words reason a regulator will actually read.
export type Purpose = {
  code: string;
  label: string;
  basis: string;
  plain: string;
};

