export function purposesFor(cls: InvestmentClass): Purpose[] {
  return cls === "ODI" ? ODI_PURPOSES : OPI_PURPOSES;
}

export function findPurpose(code: string): Purpose | undefined {
  return [...ODI_PURPOSES, ...OPI_PURPOSES].find((p) => p.code === code);
}
