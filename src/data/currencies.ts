/** Emoji flag from an ISO-3166 alpha-2 country code. */
export function flag(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}

